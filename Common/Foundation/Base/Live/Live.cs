namespace Galleon.Checkout.Foundation
{
    public class LiveComponent
    {
        //////////////////////////////////////////////////////////////////////////////////////////////////////////////// Members
        
        protected object target;

        //////////////////////////////////////////////////////////////////////////////////////////////////////////////// Components
        
        public CRUD  CRUD  { get; } = new CRUD();
        public SPMEP SPMEP { get; } = new SPMEP();
        
        //////////////////////////////////////////////////////////////////////////////////////////////////////////////// Lifecycle
        
        public LiveComponent() { }
        
        //////////////////////////////////////////////////////////////////////////////////////////////////////////////// Methods
        
        public void SetTarget(object target) => this.target = target;
        
        //////////////////////////////////////////////////////////////////////////////////////////////////////////////// OLD
        
        public virtual void Create() {}
        public virtual void OnAddedToParent(IEntity Parent) {}
    }
    public class LiveComponent<T> : LiveComponent where T : class 
    {
        public new T Target
        {
            get => target as T;
            set => target = value;
        }
    }
    
